#!/usr/bin/env python3
"""Merge public rules into this Mac's existing Clash global script and reload.
Requires macOS Ruby, Node.js and Clash Verge Rev. Private state stays outside Git.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
from datetime import datetime
from pathlib import Path
from urllib.request import Request, urlopen

REPO = Path(__file__).resolve().parent
STATE = Path.home() / 'Library/Application Support/io.github.clash-verge-rev.clash-verge-rev'
MIHOMO = '/Applications/Clash Verge.app/Contents/MacOS/verge-mihomo'


def run(args, data=None):
    p = subprocess.run(args, input=data, text=True, capture_output=True)
    if p.returncode:
        raise RuntimeError(f'{Path(args[0]).name} failed; private output suppressed')
    return p.stdout


def read_yaml(path):
    return json.loads(run(['ruby', '-ryaml', '-rjson', '-e',
                          'puts JSON.generate(YAML.load_file(ARGV[0]))', str(path)]))


def yaml_text(obj):
    return run(['ruby', '-ryaml', '-rjson', '-e',
                'puts JSON.parse(STDIN.read).to_yaml'], json.dumps(obj))


def evaluate(source, config):
    code = """const fs=require('fs'),vm=require('vm');
const x=JSON.parse(fs.readFileSync(0,'utf8'));const ctx={};vm.createContext(ctx);
vm.runInContext(x.source,ctx,{timeout:3000});
process.stdout.write(JSON.stringify(ctx.main(x.config,'codex-sync')));"""
    return json.loads(run(['node', '-e', code], json.dumps({'source': source, 'config': config})))


def rule_key(rule):
    # Policy is the penultimate field when no-resolve is present.
    parts = rule.split(',')
    return ','.join(parts[:-2] if parts[-1] == 'no-resolve' else parts[:-1])


def controller(config, path, body=None):
    addr = config.get('external-controller', '127.0.0.1:9097')
    if not re.fullmatch(r'(127\.0\.0\.1|localhost):\d+', addr):
        raise RuntimeError('Expected loopback Clash controller')
    req = Request('http://' + addr + path,
                  data=json.dumps(body).encode() if body is not None else None,
                  headers={'Authorization': 'Bearer ' + str(config.get('secret', '')),
                           'Content-Type': 'application/json'},
                  method='PUT' if body is not None else 'GET')
    with urlopen(req, timeout=15) as response:
        raw = response.read()
        return json.loads(raw) if raw else None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate without applying')
    args = parser.parse_args()
    os.umask(0o077)
    registry = read_yaml(STATE / 'profiles.yaml')
    current = next(x for x in registry['items'] if x['uid'] == registry['current'])
    uid = current['option']['rules']
    rule_profile = next(x for x in registry['items'] if x['uid'] == uid)
    rule_path = STATE / 'profiles' / rule_profile['file']
    script_path = STATE / 'profiles/Script.js'
    private_path = STATE / 'profiles/codex-local-rules.json'
    source = script_path.read_text()
    runtime = read_yaml(STATE / 'clash-verge.yaml')
    public = read_yaml(REPO / 'clash/rules.yaml')['prepend']
    if not public or len(public) != len(set(public)):
        raise RuntimeError('Public rules empty or duplicated')
    if private_path.exists():
        private = json.loads(private_path.read_text())
    else:
        original = evaluate(source, runtime)['rules']
        local = read_yaml(rule_path).get('prepend', [])
        local = [r.replace('DOMAIN-SUFFIX,https://z.ai/,', 'DOMAIN-SUFFIX,z.ai,')
                 .replace('DOMAIN-KEYWORD,linuxdo,', 'DOMAIN-SUFFIX,linux.do,') for r in local]
        private = {'rules': local + original,
                   'ai_keys': [rule_key(r) for r in original if r.endswith(',🤖AI美国节点')]}
    public_keys = {rule_key(r) for r in public}
    ai_keys = set(private['ai_keys'])
    merged = [r[:-len('PROXY')] + '🤖AI美国节点'
              if r.endswith(',PROXY') and rule_key(r) in ai_keys else r for r in public]
    merged += [r for r in private['rules'] if rule_key(r) not in public_keys]
    merged = list(dict.fromkeys(merged))
    block = '  // Rules generated by proxy-rules/sync-mac.py; local exceptions stay private.\n'
    block += '  if (!config["proxy-groups"].some(g => g.name === "PROXY")) {\n'
    block += '    config["proxy-groups"].push({name:"PROXY",type:"select",proxies:["🚀手动选择","🌏全球低延迟","🤖AI美国节点"]});\n  }\n'
    block += '  config.rules = ' + json.dumps(merged, ensure_ascii=False, indent=4) + ';'
    # Match both the original array and subsequent generated blocks.
    start = source.find('  // Rules generated by proxy-rules/sync-mac.py;')
    if start < 0:
        start = source.find('  config.rules = [')
    end = source.find('\n\n  return config;', start)
    if start < 0 or end < 0:
        raise RuntimeError('Unrecognized global script; refusing to overwrite')
    candidate_source = source[:start] + block + source[end:]
    candidate_config = evaluate(candidate_source, runtime)
    backup = STATE / 'backups-codex' / (datetime.now().strftime('%Y%m%d-%H%M%S') + '-proxy-rules-merge')
    backup.mkdir(parents=True)
    script_candidate = backup / 'candidate.js'
    config_candidate = backup / 'candidate.yaml'
    script_candidate.write_text(candidate_source)
    config_candidate.write_text(yaml_text(candidate_config))
    run(['node', '--check', str(script_candidate)])
    run([MIHOMO, '-t', '-d', str(STATE), '-f', str(config_candidate)])
    print(f'Validated: {len(public)} public rules, {len(merged)} Mac rules')
    if args.check:
        return
    writes = {script_path: candidate_source, rule_path: (REPO / 'clash/rules.yaml').read_text(),
              STATE / 'clash-verge.yaml': config_candidate.read_text(),
              STATE / 'clash-verge-check.yaml': config_candidate.read_text(),
              private_path: json.dumps(private, ensure_ascii=False, indent=2) + '\n'}
    originals = {}
    for path in writes:
        originals[path] = path.read_bytes() if path.exists() else None
        if path.exists():
            shutil.copy2(path, backup / path.name)
    try:
        for path, content in writes.items():
            path.write_text(content)
        controller(runtime, '/configs?force=true', {'path': str(STATE / 'clash-verge.yaml')})
        live = controller(runtime, '/rules')['rules']
        policies = [r.split(',')[-2] if r.endswith(',no-resolve') else r.split(',')[-1] for r in merged]
        if len(live) != len(merged) or [r['proxy'] for r in live] != policies:
            raise RuntimeError('Live rules differ after reload')
        if read_yaml(rule_path) != read_yaml(REPO / 'clash/rules.yaml'):
            raise RuntimeError('Local public rule file differs')
        print(f'Applied and reloaded: {len(live)} live rules; backup: {backup}')
    except Exception:
        for path, original in originals.items():
            if original is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(original)
        controller(runtime, '/configs?force=true', {'path': str(STATE / 'clash-verge.yaml')})
        raise


if __name__ == '__main__':
    main()
